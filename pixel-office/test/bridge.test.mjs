import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,writeFile,readFile,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {startOffice} from '../server.mjs';
import {acceptBridgeEvent} from '../lib/bridge.mjs';

const teams=[{id:'jeff',desks:[{id:'secretary'}]}];
const event={taskId:'bridge-test',eventId:'e1',title:'เชื่อม Office',team:'jeff',desk:'secretary',state:'working',text:'กำลังปรับระบบรับสถานะจาก ChatGPT'};
test('bridge rejects unknown desks and does not claim model execution or alter messages',()=>{
  const tasks=[];
  assert.throws(()=>acceptBridgeEvent({...event,desk:'invented'},teams,tasks),/ทะเบียน/);
  assert.throws(()=>acceptBridgeEvent({...event,state:'fake'},teams,tasks),/ทะเบียน/);
  assert.equal(tasks.length,0);
  const accepted=acceptBridgeEvent(event,teams,tasks,123);
  assert.equal(accepted.task.source,'chatgpt');
  assert.equal(accepted.event.time,123);
  assert.equal(accepted.task.result,undefined);
  assert.equal(acceptBridgeEvent(event,teams,tasks).duplicate,true);
  assert.equal(tasks[0].events.length,1);
});
test('bridge streams to open viewers, persists updates, rejects cross-origin writes and closes cleanly',async t=>{
  const dir=await mkdtemp(join(tmpdir(),'jeff-bridge-'));
  t.after(()=>rm(dir,{recursive:true,force:true}));
  const registry=join(dir,'agents.json');
  await writeFile(registry,JSON.stringify({agents:[{id:'director',role:'HA Director'}]}));
  let modelCalls=0;
  const options={port:0,dataDir:join(dir,'data'),registryPath:registry,run:async()=>{modelCalls++;}};
  const office=await startOffice(options);
  t.after(()=>office.close());
  const stream=await fetch(office.url+'/api/events');
  const reader=stream.body.getReader();
  assert.match(new TextDecoder().decode((await reader.read()).value),/sync/);
  const post=(body,origin=office.url)=>fetch(office.url+'/api/bridge/events',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify(body)});
  assert.equal((await post(event,'https://evil.example')).status,403);
  assert.equal((await post({...event,desk:'missing'})).status,400);
  assert.equal((await post(event)).status,200);
  const pushed=new TextDecoder().decode((await reader.read()).value);
  assert.match(pushed, /"source":"chatgpt"/);
  assert.match(pushed, /"state":"working"/);
  assert.equal((await (await post(event)).json()).duplicate,true);
  await post({...event,eventId:'e2',state:'ready',text:'เพิ่มช่องรับสถานะแล้ว'});
  const state=await (await fetch(office.url+'/api/state')).json();
  assert.equal(state.tasks[0].events.length,2);
  assert.equal(state.tasks[0].result,'เพิ่มช่องรับสถานะแล้ว');
  assert.deepEqual(state.messages,[]);
  assert.equal(modelCalls,0);
  const disk=JSON.parse(await readFile(join(dir,'data','office.json'),'utf8'));
  assert.equal(disk.tasks[0].source,'chatgpt');
  assert.equal(disk.tasks[0].state,'ready');
  await reader.cancel();
});
